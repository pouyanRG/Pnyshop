create or replace function public.enforce_pending_order_cancellation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if auth.uid() = old.user_id and not public.is_admin()
     and (
       old.status <> 'pending_payment'
       or new.status <> 'failed_payment'
       or (to_jsonb(new) - array['status', 'failure_reason', 'updated_at'])
          is distinct from
          (to_jsonb(old) - array['status', 'failure_reason', 'updated_at'])
