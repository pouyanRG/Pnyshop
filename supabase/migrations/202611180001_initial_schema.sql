create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, name, mobile, email_verified_at)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'name', ''),
    nullif(new.raw_user_meta_data ->> 'mobile', ''),
    new.email_confirmed_at
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function public.sync_profile_email_confirmation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.profiles
  set email = coalesce(new.email, ''),
      email_verified_at = new.email_confirmed_at,
      updated_at = now()
  where id = new.id
    and (email is distinct from coalesce(new.email, '')
      or email_verified_at is distinct from new.email_confirmed_at);
  return new;
end;
$$;

