create or replace function public.consume_api_rate_limit(
  p_rate_key text,
  p_window_seconds integer,
  p_max_requests integer
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_window timestamptz := clock_timestamp();
  allowed boolean;
begin
  if p_window_seconds <= 0 or p_max_requests <= 0 then
    raise exception 'Rate-limit window and request limit must be positive';
  end if;

  insert into public.api_rate_limits (rate_key, window_started_at, request_count)
  values (p_rate_key, current_window, 1)
  on conflict (rate_key) do update
  set window_started_at = case
        when public.api_rate_limits.window_started_at
             <= current_window - make_interval(secs => p_window_seconds)
          then current_window
        else public.api_rate_limits.window_started_at
      end,
      request_count = case
        when public.api_rate_limits.window_started_at
             <= current_window - make_interval(secs => p_window_seconds)
          then 1
        else public.api_rate_limits.request_count + 1
      end
  returning request_count <= p_max_requests into allowed;

  return allowed;
end;
$$;

revoke all on function public.consume_api_rate_limit(text, integer, integer) from public, anon, authenticated;

