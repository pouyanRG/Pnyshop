-- checkout با پشتیبانی از واریانت
-- =====================================================================
create or replace function public.create_checkout_order(
  p_idempotency_key text,
  p_shipping_method text,
  p_shipping_address text,
  p_postal_code text,
  p_coupon_code text,
  p_items jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_existing_order_id uuid;
  v_order_id uuid;
  v_item jsonb;
  v_product public.products%rowtype;
  v_variant public.product_variants%rowtype;
  v_variant_id uuid;
  v_coupon public.coupons%rowtype;
  v_quantity integer;
  v_unit_price numeric(14, 2);
  v_subtotal numeric(14, 2) := 0;
  v_shipping_cost numeric(14, 2);
  v_coupon_discount numeric(14, 2) := 0;
  v_total numeric(14, 2);
  v_has_items boolean := false;
begin
  if v_user_id is null then
    raise exception 'Authentication is required to place an order';
  end if;
  if p_idempotency_key is null or char_length(p_idempotency_key) not between 1 and 128 then
    raise exception 'A valid idempotency key is required';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'The cart must contain at least one item';
  end if;
  if p_shipping_address is null or char_length(trim(p_shipping_address)) < 10 then
    raise exception 'A complete shipping address is required';
  end if;

  select id into v_existing_order_id
  from public.orders
  where user_id = v_user_id and idempotency_key = p_idempotency_key;
  if v_existing_order_id is not null then
    return v_existing_order_id;
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := coalesce((v_item ->> 'qty')::integer, (v_item ->> 'quantity')::integer, 0);
    if v_quantity <= 0 then
      raise exception 'Order quantities must be positive';
    end if;

    v_variant_id := nullif(trim(v_item ->> 'variant_id'), '')::uuid;

    if v_variant_id is not null then
      select * into v_variant
      from public.product_variants
      where id = v_variant_id and is_active;
      if not found then
        raise exception 'A cart item variant is unavailable';
      end if;

      select * into v_product
      from public.products
      where id = v_variant.product_id and is_active;
      if not found then
        raise exception 'A cart item is unavailable';
      end if;
      if v_variant.stock < v_quantity then
        raise exception 'Insufficient stock for variant %',
          trim(both ' ' from concat_ws(' ', v_variant.color_name, v_variant.size));
      end if;

      v_unit_price := round(v_variant.price * (100 - v_variant.discount) / 100, 2);
    else
      select * into v_product
      from public.products
      where id = (v_item ->> 'id')::bigint and is_active;
      if not found then
        raise exception 'A cart item is unavailable';
      end if;
      if v_product.stock < v_quantity then
        raise exception 'Insufficient stock for product %', v_product.name;
      end if;

      v_unit_price := round(v_product.price * (100 - v_product.discount) / 100, 2);
    end if;

    v_subtotal := v_subtotal + v_unit_price * v_quantity;
    v_has_items := true;
  end loop;

  if not v_has_items then
    raise exception 'The cart must contain at least one valid product';
  end if;

  if exists (
    select 1
    from (
      select
        case
          when nullif(trim(item.value ->> 'variant_id'), '') is not null then null
          else (item.value ->> 'id')::bigint
        end as product_id,
        nullif(trim(item.value ->> 'variant_id'), '')::uuid as variant_id,
        sum(coalesce(
          (item.value ->> 'qty')::integer,
          (item.value ->> 'quantity')::integer,
          0
        )) as quantity
      from jsonb_array_elements(p_items) item
      group by 1, 2
    ) requested
    left join public.products product
      on product.id = requested.product_id and product.is_active
    left join public.product_variants variant
      on variant.id = requested.variant_id and variant.is_active
    where
      (
        requested.variant_id is not null
        and (variant.id is null or requested.quantity > variant.stock)
      )
      or (
        requested.variant_id is null
        and (product.id is null or requested.quantity > product.stock)
      )
  ) then
    raise exception 'Insufficient stock for a cart item';
  end if;

  if p_shipping_method = 'free' or v_subtotal >= 1000000 then
    v_shipping_cost := 0;
  elsif p_shipping_method = 'post' then
    v_shipping_cost := 35000;
  elsif p_shipping_method = 'tipax' then
    v_shipping_cost := 45000;
  else
    raise exception 'Unsupported shipping method';
  end if;

  if p_coupon_code is not null and trim(p_coupon_code) <> '' then
    select * into v_coupon
    from public.coupons
    where code = upper(trim(p_coupon_code))
    for update;
    if not found or not v_coupon.is_active
       or (v_coupon.starts_at is not null and v_coupon.starts_at > current_date)
       or (v_coupon.ends_at is not null and v_coupon.ends_at < current_date) then
      raise exception 'The coupon is not available';
    end if;
    if v_coupon.usage_limit is not null and v_coupon.used_count >= v_coupon.usage_limit then
      raise exception 'The coupon usage limit has been reached';
    end if;
    if v_subtotal < v_coupon.minimum_amount then
      raise exception 'The order does not meet the coupon minimum amount';
    end if;
    if v_coupon.audience = 'newUsers' and not exists (
      select 1 from public.profiles
      where id = v_user_id
        and created_at >= now() - make_interval(days => coalesce(v_coupon.audience_days, 30))
    ) then
      raise exception 'The coupon is restricted to new customers';
    elsif v_coupon.audience = 'oldUsers' and not exists (
      select 1 from public.profiles
      where id = v_user_id
        and created_at <= now() - make_interval(days => coalesce(v_coupon.audience_days, 365))
    ) then
      raise exception 'The coupon is restricted to existing customers';
    elsif v_coupon.audience not in ('all', 'newUsers', 'oldUsers') then
      raise exception 'The coupon audience is invalid';
    end if;
    if v_coupon.scope = 'category' and not exists (
      select 1
      from jsonb_array_elements(p_items) item
      left join public.product_variants variant
        on variant.id = nullif(trim(item.value ->> 'variant_id'), '')::uuid
      join public.products product
        on product.id = coalesce(
          (item.value ->> 'id')::bigint,
          variant.product_id
        )
      where product.category = v_coupon.scope_category
    ) then
      raise exception 'The cart does not contain a product in the coupon category';
    elsif v_coupon.scope not in ('all', 'category') then
      raise exception 'The coupon scope is invalid';
    end if;

    if v_coupon.discount_type = 'percent' then
      v_coupon_discount := v_subtotal * v_coupon.discount_value / 100;
      if v_coupon.maximum_discount is not null then
        v_coupon_discount := least(v_coupon_discount, v_coupon.maximum_discount);
      end if;
    else
      v_coupon_discount := v_coupon.discount_value;
    end if;
    v_coupon_discount := least(v_coupon_discount, v_subtotal);
  end if;

  v_total := v_subtotal + v_shipping_cost - v_coupon_discount;
  if v_total <= 0 then
    raise exception 'The order total must be positive';
  end if;

  begin
    insert into public.orders (
      user_id, idempotency_key, status, total_amount, shipping_method,
      shipping_cost, shipping_address, postal_code, coupon_code,
      coupon_discount_amount
    )
    values (
      v_user_id, p_idempotency_key, 'pending_payment', v_total, p_shipping_method,
      v_shipping_cost, p_shipping_address, coalesce(p_postal_code, ''),
      nullif(upper(trim(p_coupon_code)), ''), v_coupon_discount
    )
    returning id into v_order_id;
  exception when unique_violation then
    select id into v_order_id
    from public.orders
    where user_id = v_user_id and idempotency_key = p_idempotency_key;
    if v_order_id is null then
      raise;
    end if;
    return v_order_id;
  end;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_quantity := coalesce((v_item ->> 'qty')::integer, (v_item ->> 'quantity')::integer, 0);
    v_variant_id := nullif(trim(v_item ->> 'variant_id'), '')::uuid;

    if v_variant_id is not null then
      select * into v_variant
      from public.product_variants
      where id = v_variant_id;
      select * into v_product
      from public.products
      where id = v_variant.product_id;
      v_unit_price := round(v_variant.price * (100 - v_variant.discount) / 100, 2);
      insert into public.order_items (
        order_id, product_id, variant_id, product_name, quantity, unit_price, selected_options
      )
      values (
        v_order_id, v_product.id, v_variant.id, v_product.name, v_quantity, v_unit_price,
        jsonb_build_object(
          'color', v_item ->> 'color',
          'size', v_item ->> 'size',
          'variant_id', v_variant.id::text
        )
      );
    else
      select * into v_product
      from public.products
      where id = (v_item ->> 'id')::bigint;
      v_unit_price := round(v_product.price * (100 - v_product.discount) / 100, 2);
      insert into public.order_items (
        order_id, product_id, product_name, quantity, unit_price, selected_options
      )
      values (
        v_order_id, v_product.id, v_product.name, v_quantity, v_unit_price,
        jsonb_build_object('color', v_item ->> 'color')
      );
    end if;
  end loop;

  return v_order_id;
end;
$$;

create or replace function public.finalize_paid_order()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_coupon public.coupons%rowtype;
  v_item record;
begin
  if old.status <> 'pending_payment' then
    raise exception 'Only pending orders can be marked paid';
  end if;

  if old.coupon_code is not null then
    select * into v_coupon
    from public.coupons
    where code = old.coupon_code
    for update;
    if not found then
      raise exception 'The order coupon no longer exists';
    end if;
    if v_coupon.usage_limit is not null and v_coupon.used_count >= v_coupon.usage_limit then
      raise exception 'The coupon usage limit has been reached';
    end if;
  end if;

  for v_item in
    select variant_id, product_id, sum(quantity)::integer as quantity
    from public.order_items
    where order_id = new.id
      and (variant_id is not null or product_id is not null)
    group by variant_id, product_id
  loop
    if v_item.variant_id is not null then
      update public.product_variants
      set stock = stock - v_item.quantity, updated_at = now()
      where id = v_item.variant_id and stock >= v_item.quantity;
      if not found then
        raise exception 'Insufficient variant stock to finalize the order';
      end if;
    else
      update public.products
      set stock = stock - v_item.quantity, updated_at = now()
      where id = v_item.product_id and stock >= v_item.quantity;
      if not found then
        raise exception 'Insufficient stock to finalize the order';
      end if;
    end if;
  end loop;

  if v_coupon.id is not null then
    update public.coupons
    set used_count = used_count + 1, updated_at = now()
    where id = v_coupon.id;
  end if;
  new.paid_at := coalesce(new.paid_at, now());
  return new;
end;
$$;
