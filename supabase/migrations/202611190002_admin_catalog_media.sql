-- ---------------------------------------------------------------------
-- برندها
-- ---------------------------------------------------------------------
create table if not exists public.brands (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  slug text not null unique check (char_length(slug) between 1 and 160),
  logo_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists brands_active_order_idx
  on public.brands (is_active, id);

-- ---------------------------------------------------------------------
-- دسته‌بندی‌های درختی
-- spec_template آرایه‌ای از { key, label, type, unit? } است.
-- مثال: [{"key":"ram","label":"حافظه","type":"text","unit":"گیگابایت"}]
-- ---------------------------------------------------------------------
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  parent_id bigint references public.categories (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 120),
  slug text not null unique check (char_length(slug) between 1 and 160),
  image_url text,
  icon text not null default '',
  sort_order integer not null default 0,
  is_active boolean not null default true,
  spec_template jsonb not null default '[]'::jsonb
    check (jsonb_typeof(spec_template) = 'array'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (parent_id is null or parent_id <> id)
);

create index if not exists categories_active_parent_idx
  on public.categories (parent_id, sort_order, id) where is_active;

